package com.drdisagree.teledrive.presentation.settings

import androidx.compose.foundation.text.selection.SelectionContainer
import androidx.compose.material3.AlertDialog
import androidx.compose.material3.Button
import androidx.compose.material3.OutlinedTextField
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue

@Composable
fun LoggerKeyImportDialog(
    onConfirm: (String) -> Unit,
    onDismiss: () -> Unit
) {
    var value by remember { mutableStateOf("") }
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Import logger key") },
        text = {
            OutlinedTextField(
                value = value,
                onValueChange = { value = it },
                label = { Text("Base64 logger key") },
                supportingText = { Text("Paste the key generated by twnewkey or exported from TeleWarden.") },
                singleLine = true
            )
        },
        confirmButton = {
            Button(enabled = value.isNotBlank(), onClick = { onConfirm(value) }) {
                Text("Import")
            }
        },
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } }
    )
}

@Composable
fun LoggerKeyExportDialog(
    value: String,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Logger key") },
        text = {
            SelectionContainer {
                Text(
                    "Copy this key into open-tg with:\n\n.twsetkey $value\n\nKeep it private. Anyone with this key can decrypt logger media."
                )
            }
        },
        confirmButton = { TextButton(onClick = onDismiss) { Text("Done") } }
    )
}
